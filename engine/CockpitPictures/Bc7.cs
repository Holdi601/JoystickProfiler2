        private struct Bits
        {
            public ulong Low;
            public ulong High;

            public int Read(int n)
            {
                if (n == 0)
                    return 0;
                ulong mask = (1UL << n) - 1;
                int v = (int)(Low & mask);
                Low >>= n;
                Low |= (High & mask) << (64 - n);
                High >>= n;
                return v;
            }
        }

        private static int Lerp(int a, int b, int[] w, int i)
        {
            return (a * (64 - w[i]) + b * w[i] + 32) >> 6;
        }

        // Decodes one 16-byte block at data[at] into 16 RGBA texels (px, row by row).
        public static void DecodeBlock(byte[] data, int at, byte[] px)
        {
            Bits s = new Bits { Low = System.BitConverter.ToUInt64(data, at), High = System.BitConverter.ToUInt64(data, at + 8) };
            int mode = 0;
            while (mode < 8 && s.Read(1) == 0)
                mode++;
            if (mode >= 8)
            {
                for (int i = 0; i < 64; i++)
                    px[i] = 0;
                return;
            }
            int partition = 0, subsets = 1, rotation = 0, select = 0;
            if (mode == 0 || mode == 1 || mode == 2 || mode == 3 || mode == 7)
            {
                subsets = mode == 0 || mode == 2 ? 3 : 2;
                partition = s.Read(mode == 0 ? 4 : 6);
            }
            int ends = subsets * 2;
            if (mode == 4 || mode == 5)
            {
                rotation = s.Read(2);
                if (mode == 4)
                    select = s.Read(1);
            }
            int[,] ep = new int[6, 4];
            for (int c = 0; c < 3; c++)
                for (int e = 0; e < ends; e++)
                    ep[e, c] = s.Read(ColorBits[mode]);
            if (AlphaBits[mode] > 0)
                for (int e = 0; e < ends; e++)
                    ep[e, 3] = s.Read(AlphaBits[mode]);
            if (mode == 0 || mode == 1 || mode == 3 || mode == 6 || mode == 7)
            {
                for (int e = 0; e < ends; e++)
                    for (int c = 0; c < 4; c++)
                        ep[e, c] <<= 1;
                if (mode == 1)
                {
                    int p0 = s.Read(1), p1 = s.Read(1);
                    for (int c = 0; c < 3; c++)
                    {
                        ep[0, c] |= p0;
                        ep[1, c] |= p0;
                        ep[2, c] |= p1;
                        ep[3, c] |= p1;
                    }
                }
                else if ((ModeHasPBits & (1 << mode)) != 0)
                {
                    for (int e = 0; e < ends; e++)
                    {
                        int pb = s.Read(1);
                        for (int c = 0; c < 4; c++)
                            ep[e, c] |= pb;
                    }
                }
            }
            int pbit = (ModeHasPBits >> mode) & 1;
            for (int e = 0; e < ends; e++)
            {
                int bits = ColorBits[mode] + pbit;
                for (int c = 0; c < 3; c++)
                {
                    ep[e, c] = ep[e, c] << (8 - bits);
                    ep[e, c] = ep[e, c] | (ep[e, c] >> bits);
                }
                bits = AlphaBits[mode] + pbit;
                ep[e, 3] = ep[e, 3] << (8 - bits);
                ep[e, 3] = ep[e, 3] | (ep[e, 3] >> bits);
            }
            if (AlphaBits[mode] == 0)
                for (int e = 0; e < ends; e++)
                    ep[e, 3] = 255;
            int indexBits = mode == 0 || mode == 1 ? 3 : mode == 6 ? 4 : 2;
            int indexBits2 = mode == 4 ? 3 : mode == 5 ? 2 : 0;
            int[] w1 = indexBits == 2 ? Weight2 : indexBits == 3 ? Weight3 : Weight4;
            int[] w2 = indexBits2 == 2 ? Weight2 : Weight3;
            int[] idx = new int[16];
            for (int t = 0; t < 16; t++)
            {
                int set = subsets == 1 ? (t == 0 ? 128 : 0) : Partitions[((subsets - 2) * 64 + partition) * 16 + t];
                int n = indexBits - ((set & 0x80) != 0 ? 1 : 0);
                idx[t] = s.Read(n);
            }
            for (int t = 0; t < 16; t++)
            {
                int set = subsets == 1 ? (t == 0 ? 128 : 0) : Partitions[((subsets - 2) * 64 + partition) * 16 + t];
                set &= 3;
                int i = idx[t];
                int e0 = set * 2, e1 = set * 2 + 1;
                int r, g, b, a;
                if (indexBits2 == 0)
                {
                    r = Lerp(ep[e0, 0], ep[e1, 0], w1, i);
                    g = Lerp(ep[e0, 1], ep[e1, 1], w1, i);
                    b = Lerp(ep[e0, 2], ep[e1, 2], w1, i);
                    a = Lerp(ep[e0, 3], ep[e1, 3], w1, i);
                }
                else
                {
                    int i2 = s.Read(t == 0 ? indexBits2 - 1 : indexBits2);
                    if (select == 0)
                    {
                        r = Lerp(ep[e0, 0], ep[e1, 0], w1, i);
                        g = Lerp(ep[e0, 1], ep[e1, 1], w1, i);
                        b = Lerp(ep[e0, 2], ep[e1, 2], w1, i);
                        a = Lerp(ep[e0, 3], ep[e1, 3], w2, i2);
                    }
                    else
                    {
                        r = Lerp(ep[e0, 0], ep[e1, 0], w2, i2);
                        g = Lerp(ep[e0, 1], ep[e1, 1], w2, i2);
                        b = Lerp(ep[e0, 2], ep[e1, 2], w2, i2);
                        a = Lerp(ep[e0, 3], ep[e1, 3], w1, i);
                    }
                }
                int tmp;
                switch (rotation)
                {
                    case 1:
                        tmp = a; a = r; r = tmp;
                        break;
                    case 2:
                        tmp = a; a = g; g = tmp;
                        break;
                    case 3:
                        tmp = a; a = b; b = tmp;
                        break;
                }
                px[t * 4] = (byte)r;
                px[t * 4 + 1] = (byte)g;
                px[t * 4 + 2] = (byte)b;
                px[t * 4 + 3] = (byte)a;
            }
        }
